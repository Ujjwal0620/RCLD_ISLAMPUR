import mongoose from "mongoose";

const StudentSchema = new mongoose.Schema({
  formNo: { type: String, default: "", trim: true },
  aecCode: String,
  regnNo: { type: String, trim: true },
  enrollmentNo: String,
  admissionDate: String,
  dateOfAdmission: String,
  guardianContactNumber: String,
  alternatePhoneNumber: String,
  dueAmount: mongoose.Schema.Types.Mixed,
  paymentStatus: mongoose.Schema.Types.Mixed,
  sourceCourseLabel: String,
  importSource: String,
  sourceStudentName: String,
  sourceSex: String,
  sourceQualification: String,
  sourceAddressRaw: String,
  sourcePhone: String,
  sourceRowKey: String,
  sourceRowNo: Number,
  courseName: String,
  courseCode: String,
  course: String,
  batchId: { type: mongoose.Schema.Types.ObjectId, ref: "Batch", default: null },
  batchCode: String,
  applicantName: { type: String, default: "", trim: true },
  name: { type: String, default: "", trim: true },
  nationality: String,
  dateOfBirth: String,
  dob: String,
  sex: String,
  gender: String,
  fatherOrHusbandName: String,
  fatherName: String,
  address: String,
  presentAddress: String,
  permanentAddress: String,
  sameAsPresentAddress: Boolean,
  ward: String,
  village: String,
  po: String,
  ps: String,
  postOffice: String,
  policeStation: String,
  nearestLandmark: String,
  district: String,
  state: String,
  permanentPostOffice: String,
  permanentNearestLandmark: String,
  permanentPin: String,
  permanentDistrict: String,
  permanentState: String,
  pin: String,
  pincode: String,
  whatsappNumber: String,
  mobileNumber: { type: String, default: "", trim: true },
  phone: String,
  altPhone: String,
  email: { type: String, default: "", trim: true, lowercase: true },
  aadhaarNumber: { type: String, default: "", trim: true },
  qualification: String,
  referralId: { type: String, default: "" },
  referralName: { type: String, default: "" },
  marketingEmployeeId: { type: String, default: "" },
  marketingEmployeeName: { type: String, default: "" },
  qualifications: [{ examCourse: String, boardUniversity: String, collegeInstitute: String, year: String, percentage: String }],
  enclosures: { stampPhoto: Boolean, qualifyingCertificates: Boolean, matricAdmitCard: Boolean },
  declarationDate: String,
  declarationPlace: String,
  signatureApplicant: String,
  signatureUrl: String,
  photoUrl: String,
  hasPhoto: { type: Boolean, default: false },
  idCardNo: String, // Legacy compatibility for existing ID-card templates and records.
  idCardNumber: { type: String, default: null, trim: true },
  isIdDownloaded: { type: Boolean, default: false },
  isDownloaded: { type: Boolean, default: false }, // Legacy UI compatibility.
  idIssuedAt: { type: Date, default: null },
  lastDownloadedAt: { type: Date, default: null },
  currentSemester: Number,
  semesterStatus: { type: String, default: "Not Started" },
  semesterHistory: { type: [mongoose.Schema.Types.Mixed], default: [] },
  status: { type: String, default: "Admission Pending" }
}, { timestamps: true });

// Fast registration-code lookups used by safe bulk-import matching.
StudentSchema.index({ regnNo: 1 });

StudentSchema.index({ enrollmentNo: 1 }, {
  unique: true,
  partialFilterExpression: { enrollmentNo: { $type: "string", $gt: "" } }
});

export default mongoose.models.Student || mongoose.model("Student", StudentSchema);
